"""Cache historical CNINFO industry changes and notice-dated share capital.

All requests are public read-only data queries. No broker/model writes.
"""
from __future__ import annotations
import argparse
from concurrent.futures import ThreadPoolExecutor,as_completed
from datetime import datetime,timezone
import json
from pathlib import Path
import threading
import time
import requests
import numpy as np
import pandas as pd
from paper_futu.research_barra import ROOT,DATA,END,provider_field,sha,save

CACHE=ROOT/'data/interim/barra_metadata_asof_20261013_v1'
OUT=ROOT/'data/external/barra_metadata_asof_20261013_v1'
INDUSTRY_URL='https://webapi.cninfo.com.cn/api/stock/p_stock2110'
CAPITAL_URL='https://datacenter.eastmoney.com/securities/api/data/v1/get'
_local=threading.local()
_headers=None
_js=None


def session():
    if not hasattr(_local,'session'):
        _local.session=requests.Session();_local.session.headers.update({'User-Agent':'Mozilla/5.0'})
    return _local.session


def public_headers():
    # Public CNINFO client header generated by the installed AKShare adapter.
    global _headers,_js
    if _headers is None:
        import akshare.stock.stock_industry_cninfo as adapter
        _js=adapter.py_mini_racer.MiniRacer()
        _js.eval(adapter._get_file_content_ths('cninfo.js'))
        _headers={'Accept-Enckey':_js.call('getResCode1'),'Referer':'https://webapi.cninfo.com.cn/'}
    return dict(_headers)


def cached_request(path,url,params,method='GET'):
    source=path.with_suffix('.source.json')
    if path.exists():
        m=json.loads(source.read_text(encoding='utf-8'))
        if m['params']!=params or m['sha256']!=sha(path):raise ValueError('Cached response binding changed')
        return json.loads(path.read_text(encoding='utf-8'))
    last=None
    for attempt in range(2):
        try:
            headers=public_headers() if method=='POST' else {}
            r=session().request(method,url,params=params,headers=headers,timeout=(10,25));r.raise_for_status();j=r.json()
            if method=='POST':
                if j.get('resultcode')!=200 or 'records' not in j:raise ValueError(str(j)[:160])
                if len(j['records'])!=int(j.get('total',len(j['records']))):raise ValueError('Truncated industry history')
            elif not j.get('success') or not j.get('result'):raise ValueError(str(j)[:160])
            path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(r.content)
            save(source,dict(url=r.url,params=params,sha256=sha(path),retrieved_at=datetime.now(timezone.utc).isoformat()))
            return j
        except (requests.RequestException,ValueError) as error:last=error;time.sleep(attempt+1)
    raise RuntimeError(f'{path.name}: {last}')


def fetch_one(instrument):
    code=instrument[2:];ip=CACHE/'industry'/f'{instrument}.json'
    ij=cached_request(ip,INDUSTRY_URL,dict(scode=code,sdate='1990-01-01',edate=END),'POST')
    exchange=instrument[:2];params=dict(reportName='RPT_F10_EH_EQUITY',
        columns='SECUCODE,SECURITY_CODE,END_DATE,NOTICE_DATE,TOTAL_SHARES,LISTED_A_SHARES,LIMITED_A_SHARES',
        filter=f'(SECUCODE="{code}.{exchange}")',pageNumber='1',pageSize='500',
        sortTypes='-1',sortColumns='END_DATE',source='HSF10',client='PC')
    pages=[];page=1;total_pages=1
    while page<=total_pages:
        params['pageNumber']=str(page)
        p=CACHE/'capital'/f'{instrument}_{page}.json'
        j=cached_request(p,CAPITAL_URL,params.copy());pages.extend(j['result']['data'])
        total_pages=int(j['result'].get('pages') or 1);page+=1
        if total_pages>20:raise ValueError('Unexpected share-history pagination')
    if len(pages)!=int(j['result']['count']):raise ValueError('Share history pagination incomplete')
    return dict(instrument=instrument,industry_records=len(ij['records']),capital_records=len(pages))


def fetch(workers=4):
    stocks=sorted(pd.read_parquet(DATA/'raw_features.parquet',columns=[]).index.get_level_values('instrument').unique())
    CACHE.mkdir(parents=True,exist_ok=True);completed=[];failures=[]
    # Initialize the SDK's process-wide V8 allocator once on the main thread.
    public_headers()
    with ThreadPoolExecutor(max_workers=workers) as pool:
        jobs={pool.submit(fetch_one,s):s for s in stocks}
        for job in as_completed(jobs):
            try:completed.append(job.result())
            except Exception as error:failures.append(dict(instrument=jobs[job],error=str(error)))
            save(CACHE/'progress.json',dict(completed=len(completed),total=len(stocks),failures=failures,
                updated=datetime.now(timezone.utc).isoformat()))
            if (len(completed)+len(failures))%50==0:print('Metadata fetched',len(completed),'/',len(stocks),'failed',len(failures),flush=True)
    save(CACHE/'fetch_summary.json',dict(completed=completed,failures=failures))
    if failures:raise ValueError(f'{len(failures)} source queries failed; cached successes retained')


def industry_rows(payload,instrument,lag_days):
    rows=[]
    for r in payload['records']:
        # Historical Shenwan 2014 and successor 2021 standards only. Never take latest-only records.
        standard=r.get('F001V')
        if standard not in ['008018','008003'] or not r.get('F004V'):continue
        day=pd.Timestamp(r['VARYDATE']);floor=pd.Timestamp('2014-01-01' if standard=='008018' else '2021-11-15')
        effective=max(day,floor)
        rows.append(dict(instrument=instrument,industry='SW:'+str(r['F004V']),
            effective_date=effective,available_date=effective+pd.Timedelta(days=lag_days),
            source_url=INDUSTRY_URL+'?scode='+instrument[2:],source_change_date=day,
            classification_standard=standard,first_publication_verified=False,
            timing_policy=f'historical effective date plus {lag_days} calendar days; not an original publication archive'))
    f=pd.DataFrame(rows)
    if f.empty:return f
    # New standard supersedes old on equal dates; do not use future records.
    f['priority']=f.classification_standard.eq('008003').astype(int)
    f=f.sort_values(['available_date','priority','source_change_date']).drop_duplicates(['instrument','available_date'],keep='last')
    return f.drop(columns='priority')


def share_events(records,instrument):
    f=pd.DataFrame(records)
    if f.empty:return f
    if not f.SECURITY_CODE.astype(str).str.zfill(6).eq(instrument[2:]).all():raise ValueError('Wrong share security')
    for n in ['END_DATE','NOTICE_DATE']:f[n]=pd.to_datetime(f[n],errors='coerce')
    for n in ['TOTAL_SHARES','LISTED_A_SHARES','LIMITED_A_SHARES']:f[n]=pd.to_numeric(f[n],errors='coerce')
    # Listed unrestricted A + restricted A. Total-share fallback only when equality proves all shares are A.
    a=f.LISTED_A_SHARES+f.LIMITED_A_SHARES
    equality=np.isclose(f.LISTED_A_SHARES,f.TOTAL_SHARES,rtol=1e-10,atol=1)
    a=a.where(a.notna(),f.TOTAL_SHARES.where(equality))
    f['a_shares']=a
    if (f.a_shares>f.TOTAL_SHARES+1).any():raise ValueError('A-share capital exceeds total shares')
    f=f.dropna(subset=['END_DATE','NOTICE_DATE','a_shares'])
    f=f.loc[f.a_shares.gt(0)].copy()
    f['usable_date']=pd.concat([f.END_DATE,f.NOTICE_DATE+pd.Timedelta(days=1)],axis=1).max(axis=1)
    f=f.loc[f.usable_date.le(pd.Timestamp(END))].sort_values(['usable_date','END_DATE','NOTICE_DATE'])
    f=f.drop_duplicates('usable_date',keep='last')
    return f[['usable_date','a_shares','END_DATE','NOTICE_DATE','TOTAL_SHARES']]


def build():
    OUT.mkdir(parents=True,exist_ok=True)
    raw=pd.read_parquet(DATA/'raw_features.parquet',columns=[],filters=[('datetime','>=',pd.Timestamp('2018-01-01'))])
    stocks=sorted(raw.index.get_level_values('instrument').unique())
    calendar=pd.DatetimeIndex(pd.to_datetime((DATA/'provider/calendars/day.txt').read_text().splitlines()))
    dates=calendar[(calendar>='2018-01-01')&(calendar<=END)]
    close=provider_field('close',stocks,dates,calendar);factor=provider_field('factor',stocks,dates,calendar)
    price=close/factor.where(factor>0)
    industries={1:[],93:[]};caps=[];share_parts=[];audits=[]
    for stock in stocks:
        ip=CACHE/'industry'/f'{stock}.json';ij=json.loads(ip.read_text(encoding='utf-8'))
        for lag in industries:
            f=industry_rows(ij,stock,lag)
            if len(f):industries[lag].append(f)
        pages=[]
        for p in sorted((CACHE/'capital').glob(stock+'_*.json')):
            if p.name.endswith('.source.json'):continue
            pages.extend(json.loads(p.read_text(encoding='utf-8'))['result']['data'])
        events=share_events(pages,stock)
        if events.empty:audits.append(dict(instrument=stock,capital_missing=True));continue
        ep=events.copy();ep['instrument']=stock;share_parts.append(ep)
        daily=pd.DataFrame({'datetime':dates,'raw_close':price[stock].to_numpy()})
        daily=pd.merge_asof(daily,events,left_on='datetime',right_on='usable_date',direction='backward')
        daily['market_cap']=daily.raw_close*daily.a_shares
        daily=daily.loc[daily.market_cap.gt(0)&np.isfinite(daily.market_cap)].copy()
        daily['instrument']=stock;daily['effective_date']=daily.datetime;daily['available_date']=daily.datetime
        daily['source_url']=CAPITAL_URL+'?reportName=RPT_F10_EH_EQUITY&SECUCODE='+stock[2:]+'.'+stock[:2]
        caps.append(daily[['instrument','effective_date','available_date','market_cap','a_shares','END_DATE','NOTICE_DATE','source_url']])
        audits.append(dict(instrument=stock,capital_rows=len(daily),share_events=len(events),capital_missing=False))
    capital=pd.concat(caps,ignore_index=True)
    capital.to_parquet(OUT/'capital_pit.parquet',index=False)
    pd.concat(share_parts,ignore_index=True).to_parquet(OUT/'share_events.parquet',index=False)
    for lag,parts in industries.items():
        pd.concat(parts,ignore_index=True).to_parquet(OUT/f'industry_lag{lag}.parquet',index=False)
    pd.DataFrame(audits).to_csv(OUT/'coverage_by_stock.csv',index=False)
    artifacts={str(p):sha(p) for p in OUT.iterdir() if p.is_file() and p.name!='manifest.json'}
    sources={str(p):sha(p) for p in CACHE.rglob('*.json') if p.name not in ['progress.json','fetch_summary.json']}
    save(OUT/'manifest.json',dict(as_of=END,capital_rows=len(capital),stocks=len(stocks),
        industry_source='CNINFO historical Shenwan classification change records, 2014/2021 taxonomy floors',
        industry_timing='No original publication timestamps. Main study delays changes 93 calendar days; 1-day sensitivity also provided.',
        capital_basis='Point-in-time publicly announced A-share counts * daily unadjusted A-share close; H/B shares excluded',
        share_availability='max(change effective date, announcement date + one calendar day)',
        capital_revision_limitation='Current vendor historical archive, not a complete vintage share-register archive',
        artifacts=artifacts,sources=sources,implementation={str(Path(__file__)):sha(__file__)}))
    print('BUILD COMPLETE',len(capital),'capital rows',flush=True)


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--stage',choices=['fetch','build','all'],default='all');p.add_argument('--workers',type=int,default=4);a=p.parse_args()
    if not 1<=a.workers<=4:raise ValueError('At most four bounded public-data requests')
    from filelock import FileLock
    CACHE.mkdir(parents=True,exist_ok=True)
    with FileLock(str(CACHE/'fetch.lock'),timeout=0):
        if a.stage in ['fetch','all']:fetch(a.workers)
        if a.stage in ['build','all']:build()


if __name__=='__main__':main()
